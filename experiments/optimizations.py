"""Measures the effect of each optimization of the branch and bound algorithms.

    python -m experiments.optimizations [--problems PROBLEM ...] [--families FAMILY ...]
        [--time-limit SECONDS] [--max-seen-entries N] [--output FILE]
    python -m experiments.optimizations --summary [--output FILE]

Each graph is solved with the default optimizations, without each one of them,
with each one that isn't a default, and without any optimization, and each run
is written as a row of the output CSV file. A
run that takes longer than the time limit is stopped. The graphs of each series
grow in size, and once a configuration times out on a series, it isn't run on
its larger graphs, which are recorded as skipped.

Runs already in the output file are not repeated, so an interrupted experiment
resumes where it stopped. Each graph is generated with its own fixed seed, so
the graphs are the same every time, and their graph6 is in the output too.

Before measuring, each problem is solved once on a small graph, so that no run
pays for the imports and initializations done the first time. Runs shorter than
a tenth of a second are repeated, and the shortest time is recorded.

Besides the time, it records the nodes searched by the branch and bound, which
don't depend on the machine. For proper thinness, those searched to compute the
thinness as a lower bound are in a separate column.

At the end, and with --summary, it prints for each configuration how much slower
it is than the one with the default optimizations, and how many more nodes it searches,
as the geometric mean of the ratios over the graphs both solved, and on how many
graphs it timed out. Graphs that both solve in less than 10 milliseconds are
left out of the times, as those are mostly overhead.
"""
from sage import all
import argparse
import collections
import csv
import dataclasses
import math
import os
import time
import zlib
from collections.abc import Callable, Iterator

from cysignals.alarm import AlarmInterrupt, alarm, cancel_alarm
from sage.graphs.graph import Graph
from sage.graphs.graph_generators import graphs
from sage.misc.prandom import randint, random
from sage.misc.randstate import set_random_seed

from proper_thinness import optimizations as proper_thinness_optimizations
from proper_thinness.branch_and_bound import calculate_proper_thinness
from thinness import optimizations as thinness_optimizations
from thinness.branch_and_bound import calculate_thinness

THINNESS = 'thinness'
PROPER_THINNESS = 'proper-thinness'
SOLVERS = {THINNESS: calculate_thinness, PROPER_THINNESS: calculate_proper_thinness}
OPTIMIZATIONS = {THINNESS: thinness_optimizations, PROPER_THINNESS: proper_thinness_optimizations}

DEFAULT = 'default'
NONE = 'none'
OK = 'ok'
TIMEOUT = 'timeout'
SKIPPED = 'skipped'
DEFAULT_OUTPUT = 'experiments/optimizations.csv'
DEFAULT_TIME_LIMIT = 30
# Runs shorter than this are repeated up to MAX_REPETITIONS times in total.
MIN_MEASURED_SECONDS = 0.1
MAX_REPETITIONS = 10
# Graphs both configurations solve faster than this are left out of the time ratios.
MIN_SECONDS_FOR_RATIOS = 0.01
COLUMNS = [
    'problem', 'family', 'series', 'size', 'index', 'n', 'm', 'graph6',
    'configuration', 'status', 'value', 'seconds', 'cpu_seconds', 'nodes', 'thinness_nodes',
]


@dataclasses.dataclass
class Family:
    """Graphs of a family, generated by `generate(series, size)`, with the sizes for each problem."""
    series: list
    sizes: dict[str, list[int]]
    graphs_per_size: int
    generate: Callable[[object, int], Graph]


def random_cograph(n: int) -> Graph:
    """A single vertex, or the disjoint union or the join of two random cographs."""
    if n == 1:
        return Graph(1)
    first_order = randint(1, n - 1)
    first, second = random_cograph(first_order), random_cograph(n - first_order)
    if random() < 0.5:
        return first.disjoint_union(second, labels='integers')
    return first.join(second, labels='integers')


def crown_graph(vertices_per_side: int) -> Graph:
    """The complete bipartite graph without a perfect matching."""
    graph = graphs.CompleteBipartiteGraph(vertices_per_side, vertices_per_side)
    graph.delete_edges((i, vertices_per_side + i) for i in range(vertices_per_side))
    return graph


FAMILIES = {
    'random': Family(
        series=[0.2, 0.5, 0.8],
        sizes={THINNESS: [12, 15, 18, 21, 24], PROPER_THINNESS: [10, 12, 14, 16]},
        graphs_per_size=3,
        generate=lambda density, n: graphs.RandomGNP(n, density),
    ),
    'random-3-regular': Family(
        series=[3],
        sizes={THINNESS: [20, 24, 28, 32, 36, 40], PROPER_THINNESS: [12, 16, 20, 24]},
        graphs_per_size=3,
        generate=lambda degree, n: graphs.RandomRegular(degree, n),
    ),
    'tree': Family(
        series=[None],
        sizes={THINNESS: [50, 75, 100, 150, 200], PROPER_THINNESS: [20, 25, 30, 35, 40]},
        graphs_per_size=3,
        generate=lambda _, n: graphs.RandomTree(n),
    ),
    'cograph': Family(
        series=[None],
        sizes={THINNESS: [24, 32, 40, 48, 56, 64], PROPER_THINNESS: [14, 18, 22, 26, 30]},
        graphs_per_size=3,
        generate=lambda _, n: random_cograph(n),
    ),
    # Thinness and proper thinness k with 2k vertices.
    'complement-of-kK2': Family(
        series=[None],
        sizes={THINNESS: [4, 6, 8, 10, 12, 14], PROPER_THINNESS: [4, 6, 8, 10, 12, 14]},
        graphs_per_size=1,
        generate=lambda _, k: (graphs.CompleteGraph(2) * k).complement(),
    ),
    # Thinness k - 1 with 2k vertices.
    'crown': Family(
        series=[None],
        sizes={THINNESS: [6, 7, 8, 9, 10, 11, 12, 13], PROPER_THINNESS: [3, 4, 5, 6, 7, 8, 9, 10]},
        graphs_per_size=1,
        generate=lambda _, k: crown_graph(k),
    ),
    # k x k grids.
    'grid': Family(
        series=[None],
        sizes={THINNESS: [4, 5, 6, 7, 8, 9], PROPER_THINNESS: [3, 4, 5, 6]},
        graphs_per_size=1,
        generate=lambda _, k: graphs.Grid2dGraph(k, k),
    ),
    # Hypercubes of dimension k.
    'hypercube': Family(
        series=[None],
        sizes={THINNESS: [2, 3, 4, 5, 6], PROPER_THINNESS: [2, 3, 4, 5]},
        graphs_per_size=1,
        generate=lambda _, k: graphs.CubeGraph(k),
    ),
}


@dataclasses.dataclass
class Case:
    family: str
    series: object
    size: int
    index: int
    graph: Graph

    def key(self) -> tuple[str, str, str, str]:
        return self.family, _series_key(self.series), str(self.size), str(self.index)


def generate_cases(problem: str, families: list[str]) -> Iterator[Case]:
    """The graphs of each series of the families, by increasing size."""
    for family_name in families:
        family = FAMILIES[family_name]
        for series in family.series:
            for size in family.sizes[problem]:
                for index in range(family.graphs_per_size):
                    set_random_seed(zlib.crc32(f'{family_name}/{series}/{size}/{index}'.encode()))
                    graph = family.generate(series, size).relabel(inplace=False)
                    yield Case(family_name, series, size, index, graph)


def configurations(problem: str) -> list[tuple[str, int]]:
    """The default optimizations, without each one of them, with each other one, and without any of them."""
    optimizations = OPTIMIZATIONS[problem]
    default = optimizations.DEFAULT_OPTIMIZATIONS
    return (
        [(DEFAULT, default)]
        + [
            (f'without {optimization.name}', default & ~optimization)
            if default & optimization
            else (f'with {optimization.name}', default | optimization)
            for optimization in optimizations.Optimization
        ]
        + [(NONE, optimizations.Optimization(0))]
    )


def solve(problem: str, graph: Graph, optimizations: int, time_limit: float, max_seen_entries: int | None) -> dict:
    """The status, the value found, the seconds and CPU seconds taken, and the nodes searched.

    A run shorter than MIN_MEASURED_SECONDS is repeated, and the shortest is kept.
    The search is deterministic, so the value and the nodes are the same every time.
    """
    result = _solve_once(problem, graph, optimizations, time_limit, max_seen_entries)
    total_seconds = result['seconds']
    repetitions = 1
    while result['status'] == OK and total_seconds < MIN_MEASURED_SECONDS and repetitions < MAX_REPETITIONS:
        repetition = _solve_once(problem, graph, optimizations, time_limit, max_seen_entries)
        total_seconds += repetition['seconds']
        repetitions += 1
        if repetition['seconds'] < result['seconds']:
            result = repetition
    return result


def _solve_once(problem: str, graph: Graph, optimizations: int, time_limit: float, max_seen_entries: int | None) -> dict:
    statistics = {}
    keyword_arguments = {'optimizations': optimizations, 'statistics': statistics}
    if max_seen_entries is not None:
        keyword_arguments['max_seen_entries'] = max_seen_entries
    start, cpu_start = time.perf_counter(), time.process_time()
    alarm(time_limit)
    try:
        value = SOLVERS[problem](graph, **keyword_arguments)
        status = OK
    except AlarmInterrupt:
        value = ''
        status = TIMEOUT
    finally:
        cancel_alarm()
    return {
        'status': status,
        'value': value,
        'seconds': time.perf_counter() - start,
        'cpu_seconds': time.process_time() - cpu_start,
        # The counts are lost when the search is stopped.
        'nodes': statistics.get('nodes', '') if status == OK else '',
        'thinness_nodes': statistics.get('thinness_nodes', '') if status == OK else '',
    }


def warm_up(problem: str):
    """Solve a small graph with each configuration, so that the first measured run doesn't pay for imports."""
    for _, optimizations in configurations(problem):
        SOLVERS[problem](graphs.PetersenGraph(), optimizations=optimizations)


def run(problems: list[str], families: list[str], time_limit: float, max_seen_entries: int | None, output: str):
    rows = _read_rows(output)
    done = {_run_key(row) for row in rows}
    # The smallest size at which each configuration timed out on each series.
    timed_out_at = {}
    for row in rows:
        if row['status'] != OK:
            series_key = (row['problem'], row['family'], row['series'], row['configuration'])
            timed_out_at[series_key] = min(timed_out_at.get(series_key, math.inf), int(row['size']))

    is_new_file = not os.path.exists(output)
    with open(output, 'a', newline='') as file:
        writer = csv.DictWriter(file, COLUMNS)
        if is_new_file:
            writer.writeheader()
        for problem in problems:
            warm_up(problem)
            for case in generate_cases(problem, families):
                values = set()
                for name, optimizations in configurations(problem):
                    if (problem, *case.key(), name) in done:
                        continue
                    series_key = (problem, case.family, _series_key(case.series), name)
                    if case.size > timed_out_at.get(series_key, math.inf):
                        result = {'status': SKIPPED}
                    else:
                        result = solve(problem, case.graph, optimizations, time_limit, max_seen_entries)
                    if result['status'] == OK:
                        values.add(result['value'])
                    elif result['status'] == TIMEOUT:
                        timed_out_at[series_key] = min(timed_out_at.get(series_key, math.inf), case.size)
                    writer.writerow({
                        'problem': problem,
                        'family': case.family,
                        'series': case.series,
                        'size': case.size,
                        'index': case.index,
                        'n': case.graph.order(),
                        'm': case.graph.size(),
                        'graph6': case.graph.graph6_string(),
                        'configuration': name,
                        **result,
                    })
                    file.flush()
                    seconds = f" {result['seconds']:.3f}s" if 'seconds' in result else ''
                    nodes = f" {result['nodes']} nodes" if result.get('nodes', '') != '' else ''
                    print(
                        f"{problem} {case.family} {case.series} {case.size} #{case.index} {name}: "
                        f"{result['status']} {result.get('value', '')}{seconds}{nodes}",
                        flush=True,
                    )
                if len(values) > 1:
                    print(f'WARNING: different values for {case.graph.graph6_string()}: {sorted(values)}', flush=True)
    summarize(output)


def summarize(output: str):
    """For each configuration and family, the slowdown and the extra nodes with respect to the default optimizations, and the timeouts."""
    rows = _read_rows(output)
    by_graph = collections.defaultdict(dict)
    for row in rows:
        by_graph[row['problem'], row['family'], row['series'], row['size'], row['index']][row['configuration']] = row

    for problem in SOLVERS:
        graph_keys = [key for key in by_graph if key[0] == problem]
        if not graph_keys:
            continue
        mismatches = [key for key in graph_keys if len({row['value'] for row in by_graph[key].values() if row['status'] == OK}) > 1]
        print(f'\n{problem}: {len(graph_keys)} graphs, {len(mismatches)} with different values')
        for key in mismatches:
            print(f'  different values: {key}')
        print(f'\nTime, relative to the default optimizations, over the graphs that take at least {MIN_SECONDS_FOR_RATIOS}s:')
        _print_ratios(problem, by_graph, graph_keys, _seconds, minimum=MIN_SECONDS_FOR_RATIOS)
        print('\nNodes, relative to the default optimizations:')
        _print_ratios(problem, by_graph, graph_keys, _nodes, minimum=0)


def _print_ratios(
    problem: str,
    by_graph: dict,
    graph_keys: list,
    measure: Callable[[dict], float],
    minimum: float,
):
    """A table with a row for each configuration and a column for each family.

    Each cell is the geometric mean of the ratios between the measure of the
    configuration and that of the default optimizations, over the graphs both solved
    where at least one of them measures `minimum` or more, and the number of
    graphs the configuration didn't solve.
    """
    families = sorted({key[1] for key in graph_keys})
    print('\t'.join(['configuration', *families, 'total']))
    for name, _ in configurations(problem):
        cells = []
        for family in [*families, None]:
            ratios = []
            not_solved = 0
            for key in graph_keys:
                if family is not None and key[1] != family:
                    continue
                row, default_row = by_graph[key].get(name), by_graph[key].get(DEFAULT)
                if row is None:
                    continue
                if row['status'] != OK:
                    not_solved += 1
                elif (
                    default_row is not None
                    and default_row['status'] == OK
                    and max(measure(row), measure(default_row)) >= minimum
                ):
                    ratios.append(measure(row) / measure(default_row))
            mean = f'{math.exp(sum(map(math.log, ratios)) / len(ratios)):.2f}x' if ratios else '-'
            cells.append(mean + (f' ({not_solved} TO)' if not_solved else ''))
        print('\t'.join([name, *cells]))


def _seconds(row: dict) -> float:
    return float(row['seconds'])


def _nodes(row: dict) -> float:
    """The nodes searched, including those to compute the thinness for proper thinness, at least one."""
    return max(int(row['nodes'] or 0) + int(row['thinness_nodes'] or 0), 1)


def _read_rows(output: str) -> list[dict]:
    if not os.path.exists(output):
        return []
    with open(output, newline='') as file:
        return list(csv.DictReader(file))


def _series_key(series) -> str:
    """The series as it is written in the output file, where None is empty."""
    return '' if series is None else str(series)


def _run_key(row: dict) -> tuple[str, ...]:
    return row['problem'], row['family'], row['series'], row['size'], row['index'], row['configuration']


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--problems', nargs='+', choices=list(SOLVERS), default=list(SOLVERS))
    parser.add_argument('--families', nargs='+', choices=list(FAMILIES), default=list(FAMILIES))
    parser.add_argument('--time-limit', type=float, default=DEFAULT_TIME_LIMIT)
    parser.add_argument('--max-seen-entries', type=int)
    parser.add_argument('--output', default=DEFAULT_OUTPUT)
    parser.add_argument('--summary', action='store_true', help='only print the summary of the output file')
    arguments = parser.parse_args()
    if arguments.summary:
        summarize(arguments.output)
    else:
        run(arguments.problems, arguments.families, arguments.time_limit, arguments.max_seen_entries, arguments.output)
